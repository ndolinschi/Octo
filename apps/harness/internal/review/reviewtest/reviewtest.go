// NewRepo makes the repository: main with a few files, a feature branch that
// changes core code, a caller, a test, a lock file, generated code, a pure
// rename (Cyrillic path), a formatting-only change and a binary file. The
// bare origin has refs/pull/1/head at the feature tip. The working tree is on
// main with an untracked file.
func NewRepo(t testing.TB) *Repo {
	t.Helper()
	if gitPath == "" {
		t.Skip("git not installed")
	}
	root := t.TempDir()
	dir := filepath.Join(root, "my repo — проект")
	origin := filepath.Join(root, "origin repo.git")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	Git(t, dir, "init", "-q", "-b", "main")
	write(t, dir, "src/auth.go", authV1)
	write(t, dir, "src/session.go", sessionV1)
	write(t, dir, "src/fmt_only.go", "package auth\n\nfunc Format(a int) int {\nreturn a+1\n}\n")
	write(t, dir, "src/old name.go", "package auth\n\n// Moved keeps its content.\nfunc Moved() int { return 7 }\n")
	write(t, dir, "README.md", "# widgets\n")
	write(t, dir, "package-lock.json", "{\"lockfileVersion\":3}\n")
	write(t, dir, "assets/logo.png", "\x89PNG\r\n\x1a\n\x00\x00old")
	write(t, dir, "docs/Руководство.md", "Введение\n")
	Git(t, dir, "add", "-A")
	Git(t, dir, "commit", "-q", "-m", "base")
	base := Git(t, dir, "rev-parse", "HEAD")

	Git(t, dir, "checkout", "-q", "-b", "feature")
	write(t, dir, "src/auth.go", authV2)
	write(t, dir, "src/session.go", sessionV2)
	write(t, dir, "src/auth_test.go", "package auth\n\nimport \"testing\"\n\nfunc TestValidateToken(t *testing.T) {\n\tif ValidateToken(\"\") == nil {\n\t\tt.Fatal(\"want error\")\n\t}\n}\n")
	write(t, dir, "package-lock.json", "{\"lockfileVersion\":3,\"packages\":{\"a\":{}}}\n")
	write(t, dir, "gen/api.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n")
	write(t, dir, "src/by_header.go", "// Code generated by hand-rolled tool; DO NOT EDIT.\npackage auth\n\nvar X = 1\n")
	write(t, dir, "src/fmt_only.go", "package auth\n\nfunc Format(a int) int {\n\treturn a + 1\n}\n")
	write(t, dir, "README.md", "# widgets\n\nNow with token validation.\n")
	write(t, dir, "assets/logo.png", "\x89PNG\r\n\x1a\n\x00\x00new-and-longer")
	Git(t, dir, "mv", "src/old name.go", "src/новое имя.go")
	Git(t, dir, "add", "-A")
	Git(t, dir, "commit", "-q", "-m", "Add token validation\n\nbody")
	head := Git(t, dir, "rev-parse", "HEAD")
	Git(t, dir, "checkout", "-q", "main")

	bare := filepath.Dir(origin)
	if err := os.MkdirAll(bare, 0o755); err != nil {
		t.Fatal(err)
	}
	Git(t, bare, "init", "-q", "--bare", "-b", "main", origin)
	Git(t, dir, "remote", "add", "origin", origin)
	Git(t, dir, "push", "-q", "origin", "main", "feature")
	Git(t, origin, "update-ref", "refs/pull/1/head", head)

	dirty := filepath.Join(dir, "dirty.txt")
	write(t, dir, "dirty.txt", "uncommitted work\n")
	return &Repo{Dir: dir, Origin: origin, Base: base, Head: head, Dirty: dirty, Feature: "feature"}
}

// AddCommit adds a commit on the feature branch, publishes it as the PR head
// and returns its id.
func (r *Repo) AddCommit(t testing.TB, rel, content string) string {
	t.Helper()
	Git(t, r.Dir, "checkout", "-q", r.Feature)
	write(t, r.Dir, rel, content)
	Git(t, r.Dir, "add", "-A")
	Git(t, r.Dir, "commit", "-q", "-m", "more: "+rel)
	head := Git(t, r.Dir, "rev-parse", "HEAD")
	Git(t, r.Dir, "checkout", "-q", "main")
	Git(t, r.Origin, "fetch", "-q", r.Dir, "refs/heads/"+r.Feature+":refs/heads/"+r.Feature)
	Git(t, r.Origin, "update-ref", "refs/pull/1/head", head)
	r.Head = head
	return head
}

// PR describes the fixtures the fake gh serves.
type PR struct {
	Number int
	Title  string
	Body   string
	Author string
	// Comment is the text of a conversation comment by someone else.
	Comment string
	// Requested: the PR asks for the user's review.
	Requested bool
	State     string // OPEN by default
	Draft     bool
	// ReviewedBy is a login that has a review on the pull request at ReviewedCommit
	// (empty: the head). The fake's signed-in user is "me".
	ReviewedBy     string
	ReviewedCommit string
	// UpdatedAt overrides the update time ("2026-11-0N..." by default).
	UpdatedAt string
	// Repo is "owner/name" the pull request belongs to (default "acme/widgets", the repository
	// the fake answers for when a call names none). Head overrides the head commit (default
	// the repository's PR head).
	Repo string
	Head string
}

const defaultRepo = "acme/widgets"

func repoKey(repo string) string {
	if repo == "" || repo == defaultRepo {
		return ""
	}
	return "@" + strings.ReplaceAll(repo, "/", "__")
}

// AddParent creates a second bare repository (the fork's parent) holding main and,
// as refs/pull/<n>/head, a commit only it has. It returns the repository's path
// and that commit.
func (r *Repo) AddParent(t testing.TB, numbers ...int) (bare, head string) {
	t.Helper()
	bare = filepath.Join(filepath.Dir(r.Dir), "parent repo.git")
	Git(t, filepath.Dir(r.Dir), "init", "-q", "--bare", "-b", "main", bare)
	Git(t, r.Dir, "push", "-q", bare, "main")
	Git(t, r.Dir, "checkout", "-q", "-b", "parent-feature", "main")
	write(t, r.Dir, "parent-only.txt", "only the parent has this\n")
	Git(t, r.Dir, "add", "parent-only.txt")
	Git(t, r.Dir, "commit", "-q", "-m", "parent-only change")
	head = Git(t, r.Dir, "rev-parse", "HEAD")
	Git(t, r.Dir, "checkout", "-q", "main")
	for _, n := range numbers {
		Git(t, r.Dir, "push", "-q", bare, "parent-feature:refs/pull/"+itoa(n)+"/head")
	}
	return bare, head
}

// ForkRemotes makes the folder a clone of a fork: origin is https://<host>/<fork>.git and
// upstream https://<host>/<parent>.git (empty parent: no upstream remote). The addresses
// are rewritten with url.insteadOf to the local bare repositories, so fetches work
// while the configured URLs stay host addresses. Nothing is contacted.
func (r *Repo) ForkRemotes(t testing.TB, host, fork, forkBare, parent, parentBare string) {
	t.Helper()
	set := func(name, repo, bare string) {
		u := "https://" + host + "/" + repo + ".git"
		Git(t, r.Dir, "config", "remote."+name+".url", u)
		Git(t, r.Dir, "config", "url."+bare+".insteadOf", u)
	}
	Git(t, r.Dir, "remote", "set-url", "origin", r.Origin)
	set("origin", fork, forkBare)
	if parent != "" {
		Git(t, r.Dir, "remote", "add", "upstream", r.Origin)
		set("upstream", parent, parentBare)
	}
}

// SetRepo sets what the fake answers to `gh repo view <repo>`: fork of parent ("" = not a fork).
func (f *Fake) SetRepo(t testing.TB, repo, parent string) {
	t.Helper()
	o, n, _ := strings.Cut(repo, "/")
	v := map[string]any{"name": n, "owner": map[string]any{"login": o}, "url": "https://github.com/" + repo, "isFork": parent != "", "parent": nil}
	if parent != "" {
		po, pn, _ := strings.Cut(parent, "/")
		v["parent"] = map[string]any{"name": pn, "owner": map[string]any{"login": po}}
	}
	if err := os.WriteFile(filepath.Join(f.Dir, "repo"+repoKey(repo)+".json"), []byte(mustJSON(t, v)), 0o755); err != nil {
		t.Fatal(err)
	}
}

