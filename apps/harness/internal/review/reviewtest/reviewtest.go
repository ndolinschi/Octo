// NewFakeGH writes the script and fixtures for the repository's pull request
// (number 1, plus a second one that asks for review) and makes it the only
// `gh` on PATH. A real gh is never started.
func NewFakeGH(t testing.TB, r *Repo, prs ...PR) *Fake {
	t.Helper()
	if gitPath == "" {
		t.Skip("git not installed")
	}
	gitx.SetBinary(gitPath)
	t.Cleanup(func() { gitx.SetBinary("") })
	if len(prs) == 0 {
		prs = []PR{
			{Number: 1, Title: "Add token validation", Body: "Adds ValidateToken.", Author: "alice", Comment: "looks fine"},
			{Number: 2, Title: "Unrelated change", Body: "other", Author: "bob", Requested: true},
		}
	}
	d := t.TempDir()
	script := `#!/bin/bash
d="${0%/*}"
echo "$*" >> "$d/calls.log"
export -p > "$d/env.txt"
out() { printf '%s\n' "$(<"$1")"; }
repo=""; prev=""
for a in "$@"; do
  if [ "$prev" = "--repo" ] || [ "$prev" = "-R" ]; then repo="$a"; fi
  prev="$a"
done
if [ "$1 $2" = "repo view" ] && [ -n "$3" ] && [[ "$3" != -* ]]; then repo="$3"; fi
key=""
if [ -n "$repo" ]; then o="${repo%/*}"; o="${o##*/}"; n="${repo##*/}"; key="@${o}__${n}"; fi
# pick NAME: the fixture of the named repository, else the default one (a repository
# that has a list@key.json of its own never falls back).
pick() {
  if [ -n "$key" ] && [ -f "$d/$1$key.json" ]; then out "$d/$1$key.json"; return; fi
  if [ -n "$key" ] && [ -f "$d/list$key.json" ]; then echo "GraphQL: Could not resolve to a PullRequest with the requested number" >&2; exit 1; fi
  if [ -f "$d/$1.json" ]; then out "$d/$1.json"; return; fi
  echo "GraphQL: Could not resolve to a PullRequest with the requested number" >&2; exit 1
}
if [ -f "$d/logged_out" ]; then
  echo "To get started with GitHub CLI, please run:  gh auth login" >&2
  exit 4
fi
host="github.com"
if [ -f "$d/enterprise_host" ]; then
  # Like a gh that is logged in to the enterprise host only: it must be told the host.
  host=$(<"$d/enterprise_host")
  if [ "$GH_HOST" != "$host" ]; then
    echo "none of the git remotes configured for this repository point to a known GitHub host" >&2
    exit 1
  fi
  if [ "$1" = "api" ] && [[ " $* " != *" --hostname $host "* ]]; then
    echo "HTTP 404: Not Found (https://api.github.com/user)" >&2
    exit 1
  fi
fi
case "$1 $2" in
  "repo view")
    if [ -z "$repo" ]; then printf '{"name":"widgets","owner":{"login":"acme"},"url":"https://%s/acme/widgets"}\n' "$host"
    elif [ -f "$d/repo$key.json" ]; then out "$d/repo$key.json"
    else printf '{"name":"%s","owner":{"login":"%s"},"url":"https://%s/%s/%s","isFork":false,"parent":null}\n' "$n" "$o" "$host" "$o" "$n"; fi ;;
  "api user") echo '{"login":"me"}' ;;
  "api graphql")
    if [ -f "$d/graphql_fails" ]; then echo "HTTP 502: bad gateway" >&2; exit 1; fi
    if [[ "$*" == *"after="* && -f "$d/threads2.json" ]]; then out "$d/threads2.json"; else out "$d/threads.json"; fi ;;
  "pr list")
    if [[ "$*" == *review-requested* ]]; then pick requested; else pick list; fi ;;
  "pr view") pick "view-$3" ;;
  "pr checks") out "$d/checks.json"; exit 8 ;;
  "api --method")
    body=$(</dev/stdin)
    if [[ "$*" == *"/replies"* ]]; then
      [ -f "$d/reply_fails" ] && { echo "HTTP 422: reply failed" >&2; exit 1; }
      printf '%s\t%s\n' "$3 $4" "$body" >> "$d/replies.log"
      echo '{"id":9001,"html_url":"https://example.invalid/reply-9001"}'; exit 0
    fi
    printf '%s\n' "$body" >> "$d/posts.log"
    echo '{"id":4242,"html_url":"https://github.com/acme/widgets/pull/1#pullrequestreview-4242"}' ;;
  *) echo "fake gh: unexpected: $*" >&2; exit 2 ;;
esac
`
	put := func(name, content string) {
		if err := os.WriteFile(filepath.Join(d, name), []byte(content), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	put("gh", script)
	lists, reqs := map[string][]map[string]any{"": {}}, map[string][]map[string]any{"": {}}
	for _, p := range prs {
		rk := repoKey(p.Repo)
		repoName := p.Repo
		if repoName == "" {
			repoName = defaultRepo
		}
		state := p.State
		if state == "" {
			state = "OPEN"
		}
		head := r.Head
		if p.Head != "" {
			head = p.Head
		}
		updated := "2026-11-0" + itoa(p.Number) + "T10:00:00Z"
		if p.UpdatedAt != "" {
			updated = p.UpdatedAt
		}
		entry := map[string]any{
			"number": p.Number, "title": p.Title, "author": map[string]any{"login": p.Author}, "isDraft": p.Draft,
			"url": "https://github.com/" + repoName + "/pull/" + itoa(p.Number), "headRefName": "feature", "baseRefName": "main",
			"headRefOid": head, "additions": 10, "deletions": 2, "changedFiles": 3,
			"createdAt": "2026-11-01T10:00:00Z", "updatedAt": updated,
			"reviewDecision": "", "labels": []any{},
			"statusCheckRollup": []any{map[string]any{"__typename": "CheckRun", "status": "COMPLETED", "conclusion": "SUCCESS"}},
		}
		comments := []any{}
		if p.Comment != "" {
			comments = []any{map[string]any{"author": map[string]any{"login": "carol"}, "body": p.Comment, "createdAt": "2026-11-02T10:00:00Z"}}
		}
		entry["comments"] = comments
		latest := []any{}
		if p.ReviewedBy != "" {
			commit := p.ReviewedCommit
			if commit == "" {
				commit = head
			}
			latest = []any{map[string]any{"author": map[string]any{"login": p.ReviewedBy}, "body": "", "state": "COMMENTED",
				"commit": map[string]any{"oid": commit}}}
		}
		entry["latestReviews"] = latest
		lists[rk] = append(lists[rk], entry)
		if _, ok := reqs[rk]; !ok {
			reqs[rk] = []map[string]any{}
		}
		if p.Requested {
			reqs[rk] = append(reqs[rk], map[string]any{"number": p.Number})
		}
		view := map[string]any{}
		for k, v := range entry {
			view[k] = v
		}
		view["body"], view["state"], view["baseRefOid"], view["mergeable"] = p.Body, state, r.Base, "MERGEABLE"
		view["commits"] = []any{map[string]any{"oid": head, "messageHeadline": "Add token validation", "committedDate": "2026-11-01T09:00:00Z",
			"authors": []any{map[string]any{"login": p.Author}}}}
		view["reviews"] = []any{}
		put("view-"+itoa(p.Number)+rk+".json", mustJSON(t, view))
	}
	for rk, list := range lists {
		put("list"+rk+".json", mustJSON(t, list))
		req := reqs[rk]
		if req == nil {
			req = []map[string]any{}
		}
		put("requested"+rk+".json", mustJSON(t, req))
	}
	put("threads.json", `{"data":{"repository":{"pullRequest":{"reviewThreads":{"pageInfo":{"hasNextPage":false,"endCursor":""},"nodes":[]}}}}}`)
	put("checks.json", `[{"name":"build","state":"SUCCESS","bucket":"pass","link":"https://ci/1","workflow":"CI"}]`)

	t.Setenv("PATH", d)
	if p, err := exec.LookPath("gh"); err != nil || p != filepath.Join(d, "gh") {
		t.Fatalf("the fake gh is not the only gh on PATH: %q %v", p, err)
	}
	return &Fake{Dir: d}
}

func itoa(n int) string {
	b, _ := json.Marshal(n)
	return string(b)
}

func mustJSON(t testing.TB, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// Calls returns the argument lines of every gh invocation so far.
func (f *Fake) Calls() []string {
	b, err := os.ReadFile(filepath.Join(f.Dir, "calls.log"))
	if err != nil {
		return nil
	}
	return strings.Split(strings.TrimRight(string(b), "\n"), "\n")
}

// Posts returns the JSON bodies posted as reviews (one per line).
func (f *Fake) Posts() []string {
	b, err := os.ReadFile(filepath.Join(f.Dir, "posts.log"))
	if err != nil {
		return nil
	}
	return strings.Split(strings.TrimRight(string(b), "\n"), "\n")
}

// WritesCalled reports whether any invocation was a write: `gh api --method POST`
// (the review and its replies). Reads through `gh api` (user, graphql queries) are not.
func (f *Fake) WritesCalled() bool {
	for _, c := range f.Calls() {
		if strings.HasPrefix(c, "api ") && strings.Contains(c, "--method POST") {
			return true
		}
	}
	return false
}

// LoggedOut makes every call fail as "not logged in".
func (f *Fake) LoggedOut(t testing.TB, out bool) {
	t.Helper()
	p := filepath.Join(f.Dir, "logged_out")
	if out {
		if err := os.WriteFile(p, nil, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	_ = os.Remove(p)
}

// LastEnv is the environment the last gh call saw (`export -p` output).
func (f *Fake) LastEnv() string {
	b, _ := os.ReadFile(filepath.Join(f.Dir, "env.txt"))
	return string(b)
}

// Retitle rewrites the title and body served for a pull request.
func (f *Fake) Retitle(t testing.TB, number int, title, body string) {
	t.Helper()
	for _, name := range []string{"view-" + itoa(number) + ".json", "list.json"} {
		p := filepath.Join(f.Dir, name)
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		var v any
		_ = json.Unmarshal(b, &v)
		patch := func(m map[string]any) {
			if int(m["number"].(float64)) == number {
				m["title"] = title
				if _, ok := m["body"]; ok {
					m["body"] = body
				}
			}
		}
		switch x := v.(type) {
		case map[string]any:
			patch(x)
		case []any:
			for _, e := range x {
				patch(e.(map[string]any))
			}
		}
		if err := os.WriteFile(p, []byte(mustJSON(t, v)), 0o755); err != nil {
			t.Fatal(err)
		}
	}
}

// Enterprise makes the fake behave like a gh that knows only the host: every
// call must carry GH_HOST=host (and `gh api` also --hostname host), otherwise
// it fails the way gh does against the wrong host. It also points the
// repository's origin at https://host/acme/widgets.git (the local bare repository
// answers through url.insteadOf, so fetches still work).
func (f *Fake) Enterprise(t testing.TB, r *Repo, host string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(f.Dir, "enterprise_host"), []byte(host), 0o644); err != nil {
		t.Fatal(err)
	}
	remote := "https://" + host + "/acme/widgets.git"
	Git(t, r.Dir, "config", "remote.origin.url", remote)
	Git(t, r.Dir, "config", "url."+r.Origin+".insteadOf", remote)
	for _, name := range []string{"list.json", "view-1.json", "view-2.json"} {
		p := filepath.Join(f.Dir, name)
		b, err := os.ReadFile(p)
		if err != nil {
			continue
		}
		_ = os.WriteFile(p, []byte(strings.ReplaceAll(string(b), "https://github.com/", "https://"+host+"/")), 0o755)
	}
}

