// NewRepo makes the repository: main with a few files, a feature branch that
// changes core code, a caller, a test, a lock file, generated code, a pure
// rename (Cyrillic path), a formatting-only change and a binary file. The
// bare origin has refs/pull/1/head at the feature tip. The working tree is on
// main with an untracked file.
func NewRepo(t testing.TB) *Repo {
	t.Helper()
	if gitPath == "" {
		t.Skip("git not installed")
	}
	root := t.TempDir()
	dir := filepath.Join(root, "my repo — проект")
	origin := filepath.Join(root, "origin repo.git")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	Git(t, dir, "init", "-q", "-b", "main")
	write(t, dir, "src/auth.go", authV1)
	write(t, dir, "src/session.go", sessionV1)
	write(t, dir, "src/fmt_only.go", "package auth\n\nfunc Format(a int) int {\nreturn a+1\n}\n")
	write(t, dir, "src/old name.go", "package auth\n\n// Moved keeps its content.\nfunc Moved() int { return 7 }\n")
	write(t, dir, "README.md", "# widgets\n")
	write(t, dir, "package-lock.json", "{\"lockfileVersion\":3}\n")
	write(t, dir, "assets/logo.png", "\x89PNG\r\n\x1a\n\x00\x00old")
	write(t, dir, "docs/Руководство.md", "Введение\n")
	Git(t, dir, "add", "-A")
	Git(t, dir, "commit", "-q", "-m", "base")
	base := Git(t, dir, "rev-parse", "HEAD")

	Git(t, dir, "checkout", "-q", "-b", "feature")
	write(t, dir, "src/auth.go", authV2)
	write(t, dir, "src/session.go", sessionV2)
	write(t, dir, "src/auth_test.go", "package auth\n\nimport \"testing\"\n\nfunc TestValidateToken(t *testing.T) {\n\tif ValidateToken(\"\") == nil {\n\t\tt.Fatal(\"want error\")\n\t}\n}\n")
	write(t, dir, "package-lock.json", "{\"lockfileVersion\":3,\"packages\":{\"a\":{}}}\n")
	write(t, dir, "gen/api.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage gen\n")
	write(t, dir, "src/by_header.go", "// Code generated by hand-rolled tool; DO NOT EDIT.\npackage auth\n\nvar X = 1\n")
	write(t, dir, "src/fmt_only.go", "package auth\n\nfunc Format(a int) int {\n\treturn a + 1\n}\n")
	write(t, dir, "README.md", "# widgets\n\nNow with token validation.\n")
	write(t, dir, "assets/logo.png", "\x89PNG\r\n\x1a\n\x00\x00new-and-longer")
	Git(t, dir, "mv", "src/old name.go", "src/новое имя.go")
	Git(t, dir, "add", "-A")
	Git(t, dir, "commit", "-q", "-m", "Add token validation\n\nbody")
	head := Git(t, dir, "rev-parse", "HEAD")
	Git(t, dir, "checkout", "-q", "main")

	bare := filepath.Dir(origin)
	if err := os.MkdirAll(bare, 0o755); err != nil {
		t.Fatal(err)
	}
	Git(t, bare, "init", "-q", "--bare", "-b", "main", origin)
	Git(t, dir, "remote", "add", "origin", origin)
	Git(t, dir, "push", "-q", "origin", "main", "feature")
	Git(t, origin, "update-ref", "refs/pull/1/head", head)

	dirty := filepath.Join(dir, "dirty.txt")
	write(t, dir, "dirty.txt", "uncommitted work\n")
	return &Repo{Dir: dir, Origin: origin, Base: base, Head: head, Dirty: dirty, Feature: "feature"}
}

// AddCommit adds a commit on the feature branch, publishes it as the PR head
// and returns its id.
func (r *Repo) AddCommit(t testing.TB, rel, content string) string {
	t.Helper()
	Git(t, r.Dir, "checkout", "-q", r.Feature)
	write(t, r.Dir, rel, content)
	Git(t, r.Dir, "add", "-A")
	Git(t, r.Dir, "commit", "-q", "-m", "more: "+rel)
	head := Git(t, r.Dir, "rev-parse", "HEAD")
	Git(t, r.Dir, "checkout", "-q", "main")
	Git(t, r.Origin, "fetch", "-q", r.Dir, "refs/heads/"+r.Feature+":refs/heads/"+r.Feature)
	Git(t, r.Origin, "update-ref", "refs/pull/1/head", head)
	r.Head = head
	return head
}

// PR describes the fixtures the fake gh serves.
type PR struct {
	Number int
	Title  string
	Body   string
	Author string
	// Comment is the text of a conversation comment by someone else.
	Comment string
	// Requested: the PR asks for the user's review.
	Requested bool
	State     string // OPEN by default
}

// Fake is a fake `gh`.
type Fake struct {
	Dir string
}

// NewFakeGH writes the script and fixtures for the repository's pull request
// (number 1, plus a second one that asks for review) and makes it the only
// `gh` on PATH. A real gh is never started.
func NewFakeGH(t testing.TB, r *Repo, prs ...PR) *Fake {
	t.Helper()
	if gitPath == "" {
		t.Skip("git not installed")
	}
	gitx.SetBinary(gitPath)
	t.Cleanup(func() { gitx.SetBinary("") })
	if len(prs) == 0 {
		prs = []PR{
			{Number: 1, Title: "Add token validation", Body: "Adds ValidateToken.", Author: "alice", Comment: "looks fine"},
			{Number: 2, Title: "Unrelated change", Body: "other", Author: "bob", Requested: true},
		}
	}
	d := t.TempDir()
	script := `#!/bin/bash
d="${0%/*}"
echo "$*" >> "$d/calls.log"
export -p > "$d/env.txt"
out() { printf '%s\n' "$(<"$1")"; }
if [ -f "$d/logged_out" ]; then
  echo "To get started with GitHub CLI, please run:  gh auth login" >&2
  exit 4
fi
case "$1 $2" in
  "repo view") echo '{"name":"widgets","owner":{"login":"acme"},"url":"https://github.com/acme/widgets"}' ;;
  "pr list")
    if [[ "$*" == *review-requested* ]]; then out "$d/requested.json"; else out "$d/list.json"; fi ;;
  "pr view") out "$d/view-$3.json" ;;
  "pr checks") out "$d/checks.json"; exit 8 ;;
  "api --method")
    body=$(</dev/stdin)
    printf '%s\n' "$body" >> "$d/posts.log"
    echo '{"id":4242,"html_url":"https://github.com/acme/widgets/pull/1#pullrequestreview-4242"}' ;;
  *) echo "fake gh: unexpected: $*" >&2; exit 2 ;;
esac
`
	put := func(name, content string) {
		if err := os.WriteFile(filepath.Join(d, name), []byte(content), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	put("gh", script)
	var list, req []map[string]any
	for _, p := range prs {
		state := p.State
		if state == "" {
			state = "OPEN"
		}
		head := r.Head
		entry := map[string]any{
			"number": p.Number, "title": p.Title, "author": map[string]any{"login": p.Author}, "isDraft": false,
			"url": "https://github.com/acme/widgets/pull/" + itoa(p.Number), "headRefName": "feature", "baseRefName": "main",
			"headRefOid": head, "additions": 10, "deletions": 2, "changedFiles": 3,
			"createdAt": "2026-11-01T10:00:00Z", "updatedAt": "2026-11-0" + itoa(p.Number) + "T10:00:00Z",
			"reviewDecision": "", "labels": []any{},
			"statusCheckRollup": []any{map[string]any{"__typename": "CheckRun", "status": "COMPLETED", "conclusion": "SUCCESS"}},
		}
		list = append(list, entry)
		if p.Requested {
			req = append(req, map[string]any{"number": p.Number})
		}
		view := map[string]any{}
		for k, v := range entry {
			view[k] = v
		}
		view["body"], view["state"], view["baseRefOid"], view["mergeable"] = p.Body, state, r.Base, "MERGEABLE"
		view["commits"] = []any{map[string]any{"oid": head, "messageHeadline": "Add token validation", "committedDate": "2026-11-01T09:00:00Z",
			"authors": []any{map[string]any{"login": p.Author}}}}
		view["comments"] = []any{}
		if p.Comment != "" {
			view["comments"] = []any{map[string]any{"author": map[string]any{"login": "carol"}, "body": p.Comment, "createdAt": "2026-11-02T10:00:00Z"}}
		}
		view["reviews"] = []any{}
		put("view-"+itoa(p.Number)+".json", mustJSON(t, view))
	}
	put("list.json", mustJSON(t, list))
	if req == nil {
		req = []map[string]any{}
	}
	put("requested.json", mustJSON(t, req))
	put("checks.json", `[{"name":"build","state":"SUCCESS","bucket":"pass","link":"https://ci/1","workflow":"CI"}]`)

	t.Setenv("PATH", d)
	if p, err := exec.LookPath("gh"); err != nil || p != filepath.Join(d, "gh") {
		t.Fatalf("the fake gh is not the only gh on PATH: %q %v", p, err)
	}
	return &Fake{Dir: d}
}

func itoa(n int) string {
	b, _ := json.Marshal(n)
	return string(b)
}

func mustJSON(t testing.TB, v any) string {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// Calls returns the argument lines of every gh invocation so far.
func (f *Fake) Calls() []string {
	b, err := os.ReadFile(filepath.Join(f.Dir, "calls.log"))
	if err != nil {
		return nil
	}
	return strings.Split(strings.TrimRight(string(b), "\n"), "\n")
}

// Posts returns the JSON bodies posted as reviews (one per line).
func (f *Fake) Posts() []string {
	b, err := os.ReadFile(filepath.Join(f.Dir, "posts.log"))
	if err != nil {
		return nil
	}
	return strings.Split(strings.TrimRight(string(b), "\n"), "\n")
}

// WritesCalled reports whether any invocation was not a read (`gh api` is the
// only write the adapter makes).
func (f *Fake) WritesCalled() bool {
	for _, c := range f.Calls() {
		if strings.HasPrefix(c, "api ") {
			return true
		}
	}
	return false
}

// LoggedOut makes every call fail as "not logged in".
func (f *Fake) LoggedOut(t testing.TB, out bool) {
	t.Helper()
	p := filepath.Join(f.Dir, "logged_out")
	if out {
		if err := os.WriteFile(p, nil, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	_ = os.Remove(p)
}

// LastEnv is the environment the last gh call saw (`export -p` output).
func (f *Fake) LastEnv() string {
	b, _ := os.ReadFile(filepath.Join(f.Dir, "env.txt"))
	return string(b)
}

// Retitle rewrites the title and body served for a pull request.
func (f *Fake) Retitle(t testing.TB, number int, title, body string) {
	t.Helper()
	for _, name := range []string{"view-" + itoa(number) + ".json", "list.json"} {
		p := filepath.Join(f.Dir, name)
		b, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		var v any
		_ = json.Unmarshal(b, &v)
		patch := func(m map[string]any) {
			if int(m["number"].(float64)) == number {
				m["title"] = title
				if _, ok := m["body"]; ok {
					m["body"] = body
				}
			}
		}
		switch x := v.(type) {
		case map[string]any:
			patch(x)
		case []any:
			for _, e := range x {
				patch(e.(map[string]any))
			}
		}
		if err := os.WriteFile(p, []byte(mustJSON(t, v)), 0o755); err != nil {
			t.Fatal(err)
		}
	}
}
