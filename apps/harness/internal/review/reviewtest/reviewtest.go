// Package reviewtest builds the fixtures of the review tests: a throw-away git
// repository (in a path with spaces and Cyrillic) with a bare "origin" that
// has a pull-request ref, and a fake `gh` script that is the only gh on PATH.
// A real gh is never run: PATH is reduced to the fake's directory.
package reviewtest

import (
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/ndolinschi/Octo/apps/harness/internal/gitx"
)

// gitPath is resolved before any test replaces PATH.
var gitPath, _ = exec.LookPath("git")

// Repo is a test repository with a pull request.
type Repo struct {
	Dir     string // the working repository (path has spaces and Cyrillic)
	Origin  string // the bare remote
	Base    string // main's commit
	Head    string // the PR head's commit
	Dirty   string // an untracked file in the working tree, never to be touched
	Feature string // the branch name of the head
}

// Git runs git in dir and fails the test on error.
func Git(t testing.TB, dir string, args ...string) string {
	t.Helper()
	if gitPath == "" {
		t.Skip("git not installed")
	}
	cmd := exec.Command(gitPath, append([]string{"-C", dir}, args...)...)
	cmd.Env = append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1",
		"GIT_AUTHOR_NAME=T", "GIT_AUTHOR_EMAIL=t@example.com", "GIT_COMMITTER_NAME=T", "GIT_COMMITTER_EMAIL=t@example.com")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func write(t testing.TB, dir, rel, content string) {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

