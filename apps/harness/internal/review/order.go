func extOf(p string) string { return strings.ToLower(path.Ext(p)) }

// ImageType is the content type of an image path ("" for others).
func ImageType(p string) string { return imageExt[extOf(p)] }

func isLockfile(p string) bool { return lockfiles[strings.ToLower(path.Base(p))] }

func isGeneratedPath(p string) bool {
	lp := strings.ToLower(p)
	for _, s := range generatedSuffixes {
		if strings.HasSuffix(lp, s) {
			return true
		}
	}
	for _, d := range generatedDirs {
		if strings.HasPrefix(lp, d) || strings.Contains(lp, "/"+d) {
			return true
		}
	}
	return false
}

func hasGeneratedMarker(head []byte) bool {
	if len(head) == 0 {
		return false
	}
	if len(head) > 1024 {
		head = head[:1024]
	}
	l := strings.ToLower(string(head))
	for _, m := range generatedMarkers {
		if strings.Contains(l, m) {
			return true
		}
	}
	return false
}

var testDirs = map[string]bool{"test": true, "tests": true, "__tests__": true, "spec": true, "specs": true, "e2e": true, "testdata": true, "fixtures": true, "__mocks__": true, "testing": true}

func isTestPath(p string) bool {
	lp := strings.ToLower(p)
	for _, seg := range strings.Split(path.Dir(lp), "/") {
		if testDirs[seg] {
			return true
		}
	}
	base := path.Base(lp)
	stem := strings.TrimSuffix(base, path.Ext(base))
	switch {
	case strings.HasSuffix(base, "_test.go"), strings.HasSuffix(stem, ".test"), strings.HasSuffix(stem, ".spec"),
		strings.HasPrefix(stem, "test_"), strings.HasSuffix(stem, "_test"), strings.HasSuffix(stem, "_spec"),
		strings.HasSuffix(stem, "tests"), strings.HasSuffix(stem, "test") && len(stem) > 4 && path.Ext(base) == ".java",
		strings.HasSuffix(stem, ".stories"):
		return true
	}
	return false
}

func otherReason(p string) string {
	ext, base := extOf(p), strings.ToLower(path.Base(p))
	switch {
	case docExt[ext] || strings.HasPrefix(strings.ToLower(p), "docs/"):
		return ReasonDocs
	case assetExt[ext] || imageExt[ext] != "" && ext != ".svg":
		return ReasonAsset
	case configExt[ext] || configNames[base] || strings.HasPrefix(p, ".github/") || strings.HasPrefix(base, "."):
		return ReasonConfig
	}
	return ""
}

var (
	declRe = regexp.MustCompile(`\b(?:func|def|class|struct|interface|trait|enum|type|fn|const|let|var|function|impl|module|namespace|record|object)\s+(?:\([^)]*\)\s*)?([A-Za-z_][A-Za-z0-9_]{3,})`)
	wordRe = regexp.MustCompile(`[A-Za-z_][A-Za-z0-9_]{3,}`)
)

