type fileFacts struct {
	idx      int
	declared map[string]bool
	words    map[string]bool
}

// analyseCallers sets Group callers on the files of cands that only call into
// other changed files. A file B is an edge-out to A when a changed line of B
// mentions a name declared on a changed line of A (or A's module name). A file
// is a caller when it points at more changed files than point at it.
func analyseCallers(files []File, cands []int, text map[string]*gitx.ChangedLines) {
	if text == nil || len(cands) < 2 || len(cands) > 400 {
		return
	}
	facts := make([]fileFacts, 0, len(cands))
	declOwners := map[string]int{}
	for _, i := range cands {
		cl := text[files[i].Path]
		if cl == nil {
			cl = text[files[i].OldPath]
		}
		f := fileFacts{idx: i, declared: map[string]bool{}, words: map[string]bool{}}
		if cl != nil {
			for _, l := range cl.Added {
				for _, m := range declRe.FindAllStringSubmatch(l, -1) {
					f.declared[m[1]] = true
				}
				for _, w := range wordRe.FindAllString(l, -1) {
					f.words[w] = true
				}
			}
			for _, l := range cl.Removed {
				for _, m := range declRe.FindAllStringSubmatch(l, -1) {
					f.declared[m[1]] = true
				}
				for _, w := range wordRe.FindAllString(l, -1) {
					f.words[w] = true
				}
			}
		}
		stem := strings.TrimSuffix(path.Base(files[i].Path), path.Ext(files[i].Path))
		if len(stem) >= 4 {
			f.declared[stem] = true
		}
		for s := range f.declared {
			if stopWords[s] || stopWords[strings.ToLower(s)] {
				delete(f.declared, s)
				continue
			}
			declOwners[s]++
		}
		facts = append(facts, f)
	}
	out := make([]int, len(facts))
	in := make([]int, len(facts))
	for b := range facts {
		for a := range facts {
			if a == b {
				continue
			}
			for s := range facts[a].declared {
				if declOwners[s] == 1 && facts[b].words[s] {
					out[b]++
					in[a]++
					break
				}
			}
		}
	}
	for k, f := range facts {
		if out[k] > in[k] {
			files[f.idx].Group, files[f.idx].Reason = GroupCallers, ReasonCaller
		}
	}
}

// orderFiles sorts files into reading order and numbers them.
func orderFiles(files []File) {
	sort.SliceStable(files, func(i, j int) bool {
		a, b := files[i], files[j]
		if ra, rb := groupRank[a.Group], groupRank[b.Group]; ra != rb {
			return ra < rb
		}
		if a.Group == GroupCore {
			if la, lb := a.Added+a.Removed, b.Added+b.Removed; la != lb {
				return la > lb
			}
		}
		if a.Group == GroupMechanical {
			if a.Reason != b.Reason {
				return reasonRank(a.Reason) < reasonRank(b.Reason)
			}
		}
		return a.Path < b.Path
	})
	for i := range files {
		files[i].Order = i
	}
}

func reasonRank(r string) int {
	switch r {
	case ReasonRename:
		return 0
	case ReasonFormatting:
		return 1
	case ReasonGenerated:
		return 2
	case ReasonLockfile:
		return 3
	}
	return 4
}
