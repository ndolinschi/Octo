// CleanPath confines a memory path: relative to the memory directory (a leading
// "/memories/", "/memory/" or "/" is dropped), no traversal, no hidden or empty
// segments, no backslashes or control characters, a ".md" name of at most 80
// characters.
func CleanPath(p string) (string, error) {
	p = strings.TrimSpace(p)
	for _, pre := range []string{"/memories/", "/memory/", "memories/", "memory/", "/"} {
		if strings.HasPrefix(p, pre) {
			p = strings.TrimPrefix(p, pre)
			break
		}
	}
	if p == "" {
		return "", bad("a path is required")
	}
	if len([]rune(p)) > MaxFileName {
		return "", bad("a memory file name is at most %d characters", MaxFileName)
	}
	for _, r := range p {
		if r == '\\' || r < 0x20 || r == 0x7f {
			return "", bad("the path has a character that is not allowed")
		}
	}
	for _, seg := range strings.Split(p, "/") {
		if seg == "" || strings.HasPrefix(seg, ".") {
			return "", bad("the path must stay inside the memory directory (no .., no hidden or empty segments)")
		}
	}
	if !strings.HasSuffix(p, ".md") {
		return "", bad("memory files are markdown: the name ends in .md")
	}
	if p == IndexFileName {
		return "", bad("%s is generated by the harness from the summaries and cannot be written", IndexFileName)
	}
	return p, nil
}

// ToolInput is the memory tool's input (the semantics of Anthropic's memory tool).
type ToolInput struct {
	Command    string `json:"command"`
	Path       string `json:"path"`
	FileText   string `json:"file_text"`
	Summary    string `json:"summary"`
	OldStr     string `json:"old_str"`
	NewStr     string `json:"new_str"`
	InsertLine *int   `json:"insert_line"`
	InsertText string `json:"insert_text"`
	ViewRange  []int  `json:"view_range"`
	OldPath    string `json:"old_path"`
	NewPath    string `json:"new_path"`
}

// Index renders INDEX.md from the files' summaries.
func (s *Service) Index(ctx context.Context) (string, error) {
	files, err := s.DB.Files(ctx)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# Memory index\n\n")
	if len(files) == 0 {
		b.WriteString("(no memory files yet)\n")
	}
	for _, f := range files {
		fmt.Fprintf(&b, "- %s: %s (%d bytes, updated %s)\n", f.Path, f.Summary, f.Size, f.UpdatedAt[:10])
	}
	return b.String(), nil
}

// Command runs one memory tool command. The text is the tool result; a non-nil
// error is a refusal the model can read and adapt to.
func (s *Service) Command(ctx context.Context, in ToolInput) (string, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	switch in.Command {
	case "view":
		return s.view(ctx, in)
	case "create":
		return s.create(ctx, in)
	case "str_replace":
		return s.strReplace(ctx, in)
	case "insert":
		return s.insert(ctx, in)
	case "delete":
		p, err := CleanPath(in.Path)
		if err != nil {
			return "", err
		}
		if err := s.DB.DeleteFile(ctx, p); err != nil {
			return "", fileErr(err, p)
		}
		s.publish("memory.updated", map[string]any{"path": p, "deleted": true})
		return "Deleted " + p, nil
	case "rename":
		from, err := CleanPath(in.OldPath)
		if err != nil {
			return "", err
		}
		to, err := CleanPath(in.NewPath)
		if err != nil {
			return "", err
		}
		if err := s.DB.RenameFile(ctx, from, to); err != nil {
			if errors.Is(err, projectstore.ErrExists) {
				return "", bad("%s already exists", to)
			}
			return "", fileErr(err, from)
		}
		s.publish("memory.updated", map[string]any{"path": to, "renamed_from": from})
		return fmt.Sprintf("Renamed %s to %s", from, to), nil
	}
	return "", bad("command must be view, create, str_replace, insert, delete or rename")
}

func fileErr(err error, path string) error {
	if errors.Is(err, projectstore.ErrNotFound) {
		return bad("%s does not exist", path)
	}
	return err
}

func (s *Service) view(ctx context.Context, in ToolInput) (string, error) {
	raw := strings.TrimSpace(in.Path)
	trim := strings.Trim(raw, "/")
	if trim == "" || trim == "memories" || trim == "memory" || trim == IndexFileName || raw == "/memories/"+IndexFileName {
		idx, err := s.Index(ctx)
		return idx, err
	}
	p, err := CleanPath(raw)
	if err != nil {
		return "", err
	}
	f, err := s.DB.File(ctx, p)
	if err != nil {
		return "", fileErr(err, p)
	}
	lines := strings.Split(strings.TrimSuffix(f.Content, "\n"), "\n")
	start, end := 1, len(lines)
	if len(in.ViewRange) == 2 {
		start, end = max(in.ViewRange[0], 1), min(in.ViewRange[1], len(lines))
		if start > end {
			return "", bad("view_range is outside the file (%d lines)", len(lines))
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "Here is the content of %s (%s):\n", p, f.Summary)
	for i := start; i <= end; i++ {
		fmt.Fprintf(&b, "%6d\t%s\n", i, lines[i-1])
	}
	return b.String(), nil
}

func (s *Service) check(ctx context.Context, content, summary string, creating bool) error {
	if len(content) > MaxFileBytes {
		return bad("a memory file is at most %d bytes", MaxFileBytes)
	}
	if strings.TrimSpace(summary) == "" {
		return bad("a one-line summary is required")
	}
	if creating {
		files, err := s.DB.Files(ctx)
		if err != nil {
			return err
		}
		if len(files) >= MaxFiles {
			return bad("the memory holds at most %d files; delete one first", MaxFiles)
		}
	}
	return nil
}

func oneLine(s string) string { return clip(strings.Join(strings.Fields(s), " "), MaxSummary) }

func (s *Service) create(ctx context.Context, in ToolInput) (string, error) {
	p, err := CleanPath(in.Path)
	if err != nil {
		return "", err
	}
	if _, err := s.DB.File(ctx, p); err == nil {
		return "", bad("%s already exists; use str_replace or insert to change it", p)
	}
	content, summary := s.redact(in.FileText), oneLine(s.redact(in.Summary))
	if err := s.check(ctx, content, summary, true); err != nil {
		return "", err
	}
	if _, err := s.DB.PutFile(ctx, projectstore.MemoryFile{Path: p, Summary: summary, Content: content}); err != nil {
		return "", err
	}
	s.publish("memory.updated", map[string]any{"path": p})
	return "File created successfully at " + p, nil
}

func (s *Service) update(ctx context.Context, f projectstore.MemoryFile, content, summary string) (string, error) {
	if summary == "" {
		summary = f.Summary
	}
	if err := s.check(ctx, content, summary, false); err != nil {
		return "", err
	}
	if _, err := s.DB.PutFile(ctx, projectstore.MemoryFile{Path: f.Path, Summary: summary, Content: content}); err != nil {
		return "", err
	}
	s.publish("memory.updated", map[string]any{"path": f.Path})
	return "The memory file has been edited: " + f.Path, nil
}

func (s *Service) strReplace(ctx context.Context, in ToolInput) (string, error) {
	p, err := CleanPath(in.Path)
	if err != nil {
		return "", err
	}
	f, err := s.DB.File(ctx, p)
	if err != nil {
		return "", fileErr(err, p)
	}
	if in.OldStr == "" {
		return "", bad("old_str is required")
	}
	switch n := strings.Count(f.Content, in.OldStr); {
	case n == 0:
		return "", bad("No replacement was performed: old_str did not appear verbatim in %s", p)
	case n > 1:
		return "", bad("No replacement was performed: old_str appears %d times in %s; make it unique", n, p)
	}
	return s.update(ctx, f, strings.Replace(f.Content, in.OldStr, s.redact(in.NewStr), 1), oneLine(s.redact(in.Summary)))
}

func (s *Service) insert(ctx context.Context, in ToolInput) (string, error) {
	p, err := CleanPath(in.Path)
	if err != nil {
		return "", err
	}
	f, err := s.DB.File(ctx, p)
	if err != nil {
		return "", fileErr(err, p)
	}
	if in.InsertLine == nil {
		return "", bad("insert_line is required")
	}
	lines := strings.Split(f.Content, "\n")
	if f.Content == "" {
		lines = nil
	}
	if *in.InsertLine < 0 || *in.InsertLine > len(lines) {
		return "", bad("insert_line must be between 0 and %d", len(lines))
	}
	add := strings.Split(strings.TrimSuffix(s.redact(in.InsertText), "\n"), "\n")
	out := append(append(append([]string{}, lines[:*in.InsertLine]...), add...), lines[*in.InsertLine:]...)
	return s.update(ctx, f, strings.Join(out, "\n"), oneLine(s.redact(in.Summary)))
}

// ReadFile returns a file with its content (API).
func (s *Service) ReadFile(ctx context.Context, path string) (projectstore.MemoryFile, error) {
	p, err := CleanPath(path)
	if err != nil {
		return projectstore.MemoryFile{}, err
	}
	f, err := s.DB.File(ctx, p)
	if errors.Is(err, projectstore.ErrNotFound) {
		return f, ErrNotFound
	}
	return f, err
}

// WriteFile creates or replaces a file (API: the user edits it).
func (s *Service) WriteFile(ctx context.Context, path, content, summary string) (projectstore.MemoryFile, error) {
	p, err := CleanPath(path)
	if err != nil {
		return projectstore.MemoryFile{}, err
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	_, ferr := s.DB.File(ctx, p)
	content, summary = s.redact(content), oneLine(s.redact(summary))
	if summary == "" && ferr == nil {
		old, _ := s.DB.File(ctx, p)
		summary = old.Summary
	}
	if err := s.check(ctx, content, summary, ferr != nil); err != nil {
		return projectstore.MemoryFile{}, err
	}
	f, err := s.DB.PutFile(ctx, projectstore.MemoryFile{Path: p, Summary: summary, Content: content})
	if err == nil {
		s.publish("memory.updated", map[string]any{"path": p})
	}
	return f, err
}

// DeleteFile removes a file (API).
func (s *Service) DeleteFile(ctx context.Context, path string) error {
	p, err := CleanPath(path)
	if err != nil {
		return err
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.DB.DeleteFile(ctx, p); err != nil {
		if errors.Is(err, projectstore.ErrNotFound) {
			return ErrNotFound
		}
		return err
	}
	s.publish("memory.updated", map[string]any{"path": p, "deleted": true})
	return nil
}

// Files lists the files without content, with the generated index.
func (s *Service) Files(ctx context.Context) ([]projectstore.MemoryFile, string, error) {
	files, err := s.DB.Files(ctx)
	if err != nil {
		return nil, "", err
	}
	idx, err := s.Index(ctx)
	return files, idx, err
}
